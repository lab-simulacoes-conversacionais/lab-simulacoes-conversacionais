-- RF-09, RN-06: cada pergunta que o curador faz ao personagem no modo de teste, antes de aprovar.
-- O teste não é sessão de turma: a tabela não referencia sessao nem mensagem, e nada daqui entra nas
-- métricas. Só o curador digita, então não há dado de aluno. A retenção do RN-33 cobre as conversas das
-- sessões, não estas (ver o README, "Modo de teste do cenário").
CREATE TABLE pergunta_de_teste (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cenario_versao_id   BIGINT      NOT NULL REFERENCES cenario_versao (id),
    curador_id          BIGINT      NOT NULL REFERENCES usuario (id),
    pergunta            TEXT        NOT NULL CHECK (btrim(pergunta) <> ''),
    -- RN-20: a pergunta bloqueada não chega ao modelo; a resposta bloqueada não é guardada.
    pergunta_bloqueada  BOOLEAN     NOT NULL DEFAULT false,
    resposta_bloqueada  BOOLEAN     NOT NULL DEFAULT false,
    resposta            TEXT,
    -- Como na mensagem da sala, é o teste que aponta para os metadados (RNF-10, RNF-13).
    resposta_ia_meta_id BIGINT      REFERENCES resposta_ia_meta (id) ON DELETE SET NULL,
    -- A devolução fecha a rodada de teste: só as perguntas sem devolução contam para aprovar (RN-06).
    devolucao_id        BIGINT      REFERENCES devolucao (id),
    criado_em           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_pergunta_de_teste_desfecho CHECK (
        (pergunta_bloqueada AND NOT resposta_bloqueada AND resposta IS NULL AND resposta_ia_meta_id IS NULL)
        OR (NOT pergunta_bloqueada AND resposta_bloqueada AND resposta IS NULL)
        OR (NOT pergunta_bloqueada AND NOT resposta_bloqueada AND resposta IS NOT NULL AND btrim(resposta) <> ''))
);

-- A rodada em aberto de cada curador numa versão: a contagem do RN-06, o histórico enviado ao modelo e
-- o fechamento na devolução.
CREATE INDEX ix_pergunta_de_teste_rodada ON pergunta_de_teste (cenario_versao_id, curador_id)
    WHERE devolucao_id IS NULL;
