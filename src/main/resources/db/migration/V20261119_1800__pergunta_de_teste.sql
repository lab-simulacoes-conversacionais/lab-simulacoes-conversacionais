-- RF-09, RN-06: cada pergunta que o curador faz ao personagem no modo de teste, antes de aprovar.
-- O teste não é sessão de turma: a tabela não referencia sessao nem mensagem, e nada daqui entra nas
-- métricas. Só o curador digita, então não há dado de aluno. A retenção do RN-33 cobre as conversas das
-- sessões, não estas (ver o README, "Modo de teste do cenário").
--
-- A linha é reservada (PENDENTE) antes de chamar a IA, com o cenário travado, e a mesma linha recebe o
-- resultado depois. Assim o teto de perguntas (RNF-13) vale mesmo com pedidos ao mesmo tempo, e a
-- resposta paga nunca fica sem a pergunta que a gerou.
CREATE TABLE pergunta_de_teste (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cenario_versao_id   BIGINT      NOT NULL REFERENCES cenario_versao (id),
    curador_id          BIGINT      NOT NULL REFERENCES usuario (id),
    -- O mesmo limite do campo da pergunta na sala (1000 caracteres).
    pergunta            TEXT        NOT NULL CHECK (btrim(pergunta) <> '' AND char_length(pergunta) <= 1000),
    -- PENDENTE: reservada, a IA ainda não terminou. CONCLUIDA: a resposta passou pelo filtro e foi
    -- exibida. PERGUNTA_BLOQUEADA e RESPOSTA_BLOQUEADA: o filtro bloqueou (RN-20). FALHA: o provedor ou a
    -- moderação falharam; com os metadados, se a resposta já tinha sido gerada.
    situacao            TEXT        NOT NULL DEFAULT 'PENDENTE'
                        CHECK (situacao IN ('PENDENTE', 'CONCLUIDA', 'PERGUNTA_BLOQUEADA', 'RESPOSTA_BLOQUEADA',
                                            'FALHA')),
    -- Só a resposta exibida é guardada.
    resposta            TEXT,
    -- Como na mensagem da sala, é o teste que aponta para os metadados (RNF-10, RNF-13). Cada resposta da
    -- IA pertence a uma pergunta só.
    resposta_ia_meta_id BIGINT      UNIQUE REFERENCES resposta_ia_meta (id) ON DELETE SET NULL,
    -- A devolução fecha a rodada de teste: só as perguntas sem devolução contam (RN-06) e ocupam o teto.
    devolucao_id        BIGINT      REFERENCES devolucao (id),
    criado_em           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_pergunta_de_teste_resposta CHECK (
        (situacao = 'CONCLUIDA') = (resposta IS NOT NULL)
        AND (resposta IS NULL OR btrim(resposta) <> '')),
    -- A pendente ainda não chegou ao fim, e a pergunta bloqueada nunca chega ao modelo.
    CONSTRAINT ck_pergunta_de_teste_metadados CHECK (
        situacao NOT IN ('PENDENTE', 'PERGUNTA_BLOQUEADA') OR resposta_ia_meta_id IS NULL)
);

-- A rodada em aberto de cada curador numa versão: o teto, a contagem do RN-06, o histórico enviado ao
-- modelo e o fechamento na devolução.
CREATE INDEX ix_pergunta_de_teste_rodada ON pergunta_de_teste (cenario_versao_id, curador_id)
    WHERE devolucao_id IS NULL;
