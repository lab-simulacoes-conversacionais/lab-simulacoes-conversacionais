-- RN-20: cada pergunta ou resposta bloqueada pelo filtro de conteúdo abre um caso na fila do curador.
-- Os textos são copiados, como na sinalização, para o caso sobreviver à retenção das mensagens (RN-33).
CREATE TABLE caso_bloqueado (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id           BIGINT      NOT NULL REFERENCES sessao (id),
    cenario_versao_id   BIGINT      NOT NULL REFERENCES cenario_versao (id),
    origem              TEXT        NOT NULL CHECK (origem IN ('PERGUNTA', 'RESPOSTA')),
    pergunta            TEXT        NOT NULL,
    -- Só na resposta: na pergunta, o trecho bloqueado é a própria pergunta.
    trecho_bloqueado    TEXT,
    categorias          TEXT[]      NOT NULL DEFAULT '{}',
    -- Como na sinalização, a referência pode ficar nula se a retenção apagar os metadados.
    resposta_ia_meta_id BIGINT      REFERENCES resposta_ia_meta (id) ON DELETE SET NULL,
    -- Os demais valores vêm com a triagem (RF-24). Sem CHECK, para a RF-24 não precisar removê-lo.
    status              TEXT        NOT NULL DEFAULT 'ABERTO',
    ocorrido_em         TIMESTAMPTZ NOT NULL,
    criado_em           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_caso_bloqueado_trecho CHECK ((origem = 'RESPOSTA') = (trecho_bloqueado IS NOT NULL)),
    CONSTRAINT ck_caso_bloqueado_meta CHECK (origem = 'RESPOSTA' OR resposta_ia_meta_id IS NULL),
    -- Um evento reprocessado depois de um reinício não abre o caso duas vezes.
    CONSTRAINT uq_caso_bloqueado_ocorrencia UNIQUE (sessao_id, ocorrido_em)
);

CREATE INDEX ix_caso_bloqueado_status ON caso_bloqueado (status, ocorrido_em);
