-- RF-10, RN-06: o checklist que o curador conferiu ao aprovar uma versão, e quantas perguntas de teste
-- ele tinha feito ao personagem. Uma linha por versão aprovada: a versão é aprovada uma vez só e não
-- muda mais (RN-08), então o checklist dela também não.
--
-- Só se grava checklist completo, com pelo menos 5 perguntas: o domínio recusa a aprovação antes, e as
-- restrições abaixo repetem a regra no banco.
CREATE TABLE checklist_curadoria (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cenario_versao_id   BIGINT      NOT NULL UNIQUE REFERENCES cenario_versao (id),
    curador_id          BIGINT      NOT NULL REFERENCES usuario (id),
    fatos_conferidos    BOOLEAN     NOT NULL CHECK (fatos_conferidos),
    linguagem_adequada  BOOLEAN     NOT NULL CHECK (linguagem_adequada),
    objetivos_coerentes BOOLEAN     NOT NULL CHECK (objetivos_coerentes),
    limites_respeitados BOOLEAN     NOT NULL CHECK (limites_respeitados),
    perguntas_de_teste  INTEGER     NOT NULL CHECK (perguntas_de_teste >= 5),
    criado_em           TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Como a versão aprovada (RN-08), o checklist da aprovação não muda nem é apagado.
CREATE FUNCTION impede_alterar_checklist_curadoria() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'O checklist de curadoria % é imutável (RN-06, RN-08)', OLD.id
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_checklist_curadoria_imutavel
    BEFORE UPDATE OR DELETE ON checklist_curadoria
    FOR EACH ROW
    EXECUTE FUNCTION impede_alterar_checklist_curadoria();
