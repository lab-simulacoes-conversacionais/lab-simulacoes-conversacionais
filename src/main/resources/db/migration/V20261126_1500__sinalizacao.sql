-- RF-23, RN-21: professor e curador sinalizam uma resposta da IA com possível erro.
-- A sinalização copia o que a triagem precisa (Stack, seção 6): a pergunta e a resposta inteiras, os dados
-- da sessão e os metadados da resposta. As referências ficam nulas quando a retenção (RN-33) apaga a
-- mensagem, os metadados ou a própria sessão, e a sinalização continua completa.
CREATE TABLE sinalizacao (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id             BIGINT      REFERENCES sessao (id) ON DELETE SET NULL,
    -- Copiados da sessão, para a sinalização não depender dela.
    sessao_iniciada_em    TIMESTAMPTZ NOT NULL,
    sessao_professor_id   BIGINT      NOT NULL REFERENCES usuario (id),
    -- As versões de cenário nunca são apagadas (RN-08, RN-33); o cenário sai da versão.
    cenario_versao_id     BIGINT      NOT NULL REFERENCES cenario_versao (id),
    mensagem_id           BIGINT      REFERENCES mensagem (id) ON DELETE SET NULL,
    resposta_ia_meta_id   BIGINT      REFERENCES resposta_ia_meta (id) ON DELETE SET NULL,
    -- Provedor, modelo e versão do prompt, copiados de resposta_ia_meta. Nulo só numa resposta antiga
    -- gravada sem metadados. O CHECK confere apenas o objeto, para uma chave nova não exigir alterá-lo.
    metadados_da_resposta JSONB       CHECK (jsonb_typeof(metadados_da_resposta) = 'object'),
    pergunta              TEXT        NOT NULL,
    resposta              TEXT        NOT NULL,
    respondida_em         TIMESTAMPTZ NOT NULL,
    tipo                  TEXT        NOT NULL
                          CHECK (tipo IN ('ERRO_HISTORICO', 'ERRO_CIENTIFICO', 'ANACRONISMO', 'SAIDA_DO_PERSONAGEM',
                                          'CONTEUDO_INADEQUADO')),
    gravidade_percebida   TEXT        NOT NULL CHECK (gravidade_percebida IN ('LEVE', 'MODERADA', 'GRAVE')),
    -- O limite de 500 caracteres fica na aplicação, para mudar sem alterar a restrição (RNF-12).
    justificativa         TEXT        NOT NULL CHECK (btrim(justificativa) <> ''),
    sinalizado_por_id     BIGINT      NOT NULL REFERENCES usuario (id),
    -- Com quem sinalizou: a sinalização grave do professor suspende o cenário (RN-23a, RF-25).
    perfil                TEXT        NOT NULL CHECK (perfil IN ('PROFESSOR', 'CURADOR')),
    -- Os demais valores vêm com a triagem (RF-24). Sem CHECK, para a RF-24 não precisar removê-lo.
    status                TEXT        NOT NULL DEFAULT 'PENDENTE',
    criada_em             TIMESTAMPTZ NOT NULL,
    -- Uma sinalização por pessoa e mensagem. Depois da retenção, mensagem_id nulo não colide.
    CONSTRAINT uq_sinalizacao_mensagem_por_pessoa UNIQUE (mensagem_id, sinalizado_por_id)
);

-- A fila da triagem (RF-24) e as contagens por versão (RN-23c, RN-29).
CREATE INDEX ix_sinalizacao_status ON sinalizacao (status, criada_em);
CREATE INDEX ix_sinalizacao_versao ON sinalizacao (cenario_versao_id);
